def rasterise(html_path: Path, out_png: Path, width: int = 1800) -> None:
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        print("playwright not importable — skipping the PNG; open banner.html and shoot #shot")
        return
    from PIL import Image

    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_context(
            viewport={"width": W + 100, "height": H + 100}, device_scale_factor=2
        ).new_page()
        page.goto(html_path.as_uri(), wait_until="networkidle")
        page.wait_for_timeout(1200)  # webfonts
        page.query_selector("#shot").screenshot(path=str(out_png))
        browser.close()

    im = Image.open(out_png).convert("RGB")
    im.resize((width, round(im.height * width / im.width)), Image.LANCZOS).save(
        out_png, optimize=True
    )
    print(f"wrote {out_png} ({out_png.stat().st_size // 1024} KB)")


