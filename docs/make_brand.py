"""Generate the project mark and the README banner.

Nothing here is drawn by hand. The mark is the level sets of `rho - r(theta)` around a
body from the same six-harmonic family the Flow Lab manipulates — which is to say, it is
the surrogate's own input (`flowsurrogate.geometry.level_set`) rendered as a logo, read
in a coordinate that dilates downstream so the levels trail off like a wake. The banner
puts that mark over a second contour field and four numbers this repo actually measured.

Both follow the Calque charte the platform is skinned with: paper, one orange used only
as a measure ramp, nothing filled that does not carry a quantity, a 40px type ceiling and
no display face.

Run (the platform venv has both matplotlib and playwright):

    engine-copilot/.venv/bin/python docs/make_brand.py

Writes `logo.svg`, `banner.html` and `banner.png` next to this file. Without playwright
the HTML is still written; rasterise it any way you like at 1600x372, DPR 2.
"""

from __future__ import annotations

import sys
import tempfile
