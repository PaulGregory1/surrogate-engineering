import numpy as np
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent

# Calque tokens (mirrored from engine-copilot/frontend/src/index.css).
PAPER, INK, INK3, LINE, LINE2, BURNT = "#FBFAF9", "#0D0C0B", "#9C9691", "#E9E5E1", "#D6D0CA", "#B03E00"
RAMP = ["#FFC68A", "#FF9436", "#FF6A00", "#EC6008", "#963705"]  # measure ramp, min -> critical

FONTS = (
    "https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500"
    "&family=Instrument+Sans:wght@400;500;600&family=Instrument+Serif:wght@400&display=swap"
)


# ======================================================================================
# The mark
# ======================================================================================

MODES = (2, 3, 4)
COEFFS = np.array([0.085, -0.045, 0.055, 0.018, -0.052, 0.012])  # mildly asymmetric body
LEVELS = [0.0, 0.30, 0.68, 1.12, 1.64, 2.26]  # in units of r0; 0 is the body itself
CX, CY, SCALE, WAKE = 46.5, 50.0, 15.0, 0.42  # viewBox units; WAKE = downstream dilation


def _radius(theta: np.ndarray) -> np.ndarray:
    f = np.ones_like(theta)
    for j, k in enumerate(MODES):
        f = f + COEFFS[2 * j] * np.cos(k * theta) + COEFFS[2 * j + 1] * np.sin(k * theta)
    return f


def _mark_field(n: int = 520, half: float = 3.6):
    g = np.linspace(-half, half, n)
    X, Y = np.meshgrid(g, g)
    Xw = X / (1.0 + WAKE / (1.0 + np.exp(-1.6 * (X - 0.4))))
    return X, Y, np.hypot(Xw, Y) - _radius(np.arctan2(Y, Xw))


def _iso_paths(X, Y, phi, level, sx=1.0, sy=1.0, ox=0.0, oy=0.0, step=4, close=True, min_pts=8):
    """Marching-squares polylines of {phi == level} as SVG path data."""
    segs = plt.contour(X, Y, phi, levels=[level]).allsegs[0]
    out = []
    for seg in segs:
        if len(seg) < min_pts:
            continue
        pts = [(ox + x * sx, oy + y * sy) for x, y in seg[::step]]
        d = "M" + " L".join(f"{a:.1f} {b:.1f}" for a, b in pts)
        out.append(d + " Z" if close else d)
    plt.close("all")
    return out


def build_logo() -> str:
    X, Y, phi = _mark_field()
    rings = [_iso_paths(X, Y, phi, lv, SCALE, -SCALE, CX, CY) for lv in LEVELS]

    # The body is drawn, not filled: an unfilled core keeps the mark a *field* rather
    # than an object, and the level sets read as level sets rather than a halo.
    lines = []
    for i, level_paths in enumerate(rings):
        # Ink is gained as the level grows, which is the ramp read in its own direction:
        # the innermost line is the minimum of the field, the outermost the critical end.
        w = 2.1 + 0.20 * i
        for d in level_paths:
            lines.append(
                f'<path d="{d}" fill="none" stroke="{RAMP[min(i, len(RAMP) - 1)]}" '
                f'stroke-width="{w:.2f}" stroke-linejoin="round"/>'
            )
    tile = 'x="1.6" y="1.6" width="96.8" height="96.8" rx="21" ry="21"'

    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="100" height="100" role="img" aria-label="Surrogate Engineering">
  <title>Surrogate Engineering</title>
  <!-- Level sets of rho - r(theta) around a Fourier body: the field the surrogate
       takes as input. Nothing is filled; the ramp darkens outwards, so a line's weight
       is the level it carries. Generated by docs/make_brand.py — do not hand-edit. -->
  <defs><clipPath id="sq-tile"><rect {tile}/></clipPath></defs>
  <rect {tile} fill="{PAPER}"/>
  <g clip-path="url(#sq-tile)">
{chr(10).join("    " + line for line in lines)}
  </g>
  <rect {tile} fill="none" stroke="{LINE2}" stroke-width="1.4"/>
</svg>
"""
    (HERE / "logo.svg").write_text(svg)
    print(f"wrote {HERE / 'logo.svg'}")
    return svg


# ======================================================================================
# The banner
# ======================================================================================

W, H = 1600, 372
BG_LEVELS = 26

# Every figure below is measured, and lives in flow-surrogate/RESULTS.md or
# results/optimization.json. Nothing here is rounded up for effect.
