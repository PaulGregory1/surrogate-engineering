"""Generate the project mark — the dot "C".

Nothing here is drawn by hand. The C is a square lattice of cells kept inside an
annulus with a wedge cut out on the right; the top and bottom arcs land on exactly two
rows, the back on two columns. Two quantities drive what a cell looks like:

* its **radius** follows the horizontal axis — smallest against the mouth, largest at the
  back of the C, a ratio of about 3;
* its **colour** is read off the vertical axis on the Calque measure ramp, so a row of
  cells shares a colour, the way the reference plate does.

The ramp bottoms out at `#963705`, not in a red: the charte has no red, and introducing
one would break how the orange reads everywhere else.

Run (any venv here with numpy — `engine-copilot/.venv` matches `make_brand.py`):

    engine-copilot/.venv/bin/python docs/make_logo.py

Writes `logo.svg` (the mark on its paper tile — this is the file the banner and the app's
favicon both use), plus `logo-plain.svg` (no tile, for a lockup) and `logo-dark.svg` (the
ramp re-cut for an ink ground). `make_brand.py` imports `tile_svg()` from here rather than
holding a second copy of the artwork, so this file is the mark's only definition.

It replaced a mark built from the level sets of `rho - r(theta)` — the surrogate's own
input rendered as a logo. That one is in the history, at `make_brand.py`'s `build_logo()`
before this change, if it is ever wanted back.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent

# Calque tokens (mirrored from engine-copilot/frontend/src/index.css).
PAPER, LINE2 = "#FBFAF9", "#D6D0CA"

# Measure ramp, min -> critical. The dark set keeps the same steps legible on ink.
RAMP = [(0.00, "#FFC68A"), (0.30, "#FF9436"), (0.56, "#FF6A00"),
        (0.80, "#EC6008"), (1.00, "#963705")]
RAMP_DARK = [(0.00, "#FFE3CC"), (0.30, "#FFC68A"), (0.56, "#FF9436"),
             (0.80, "#FF6A00"), (1.00, "#D14E04")]

CX = CY = 50.0          # viewBox units
STEP = 7.9              # lattice pitch
R_IN, R_OUT = 22.0, 38.0
A0, A1 = 58.0, 302.0    # the mouth: the sweep runs anticlockwise from A0 round to A1
R_SMALL, R_LARGE = 1.25, 3.70
Y_LO, Y_HI = 12.0, 88.0  # the span the colour ramp is read over


def _ramp(t: float, stops=RAMP) -> str:
    t = float(np.clip(t, 0.0, 1.0))
    for (t0, c0), (t1, c1) in zip(stops, stops[1:]):
        if t <= t1:
            f = (t - t0) / (t1 - t0)
            a = [int(c0[i:i + 2], 16) for i in (1, 3, 5)]
            b = [int(c1[i:i + 2], 16) for i in (1, 3, 5)]
            return "#%02X%02X%02X" % tuple(round(x + (y - x) * f) for x, y in zip(a, b))
    return stops[-1][1]


def cells() -> list[tuple[float, float]]:
    """The lattice points the C keeps."""
    out = []
    for i in range(-6, 7):
        for j in range(-6, 7):
            x, y = CX + i * STEP, CY + j * STEP
            dx, dy = x - CX, CY - y
            if not (R_IN <= np.hypot(dx, dy) <= R_OUT):
                continue
            if not (A0 <= np.rad2deg(np.arctan2(dy, dx)) % 360 <= A1):
                continue
            out.append((x, y))
    return out


def _radius(x: float, x0: float, x1: float) -> float:
    return R_SMALL + (R_LARGE - R_SMALL) * (1 - (x - x0) / (x1 - x0))


def dots(stops=RAMP) -> str:
    """The dots, wrapped in the translation that centres them in the viewBox.

    The mark is not symmetric — the mouth eats into the right — so its bounding box does
    not sit in the middle of the 100 x 100 canvas on its own. Centring here means the file
    drops into a lockup or a favicon without anyone having to nudge it. The translation is
    applied to the group, so radii (read off x) and colours (read off y) are untouched.
    """
    pts = cells()
    x0, x1 = min(p[0] for p in pts), max(p[0] for p in pts)
    rs = {(x, y): _radius(x, x0, x1) for x, y in pts}
    bx = [x + s * r for (x, _), r in rs.items() for s in (-1, 1)]
    by = [y + s * r for (_, y), r in rs.items() for s in (-1, 1)]
    dx, dy = CX - (min(bx) + max(bx)) / 2, CY - (min(by) + max(by)) / 2
    body = "\n    ".join(
        f'<circle cx="{x:.2f}" cy="{y:.2f}" r="{rs[(x, y)]:.2f}" '
        f'fill="{_ramp((y - Y_LO) / (Y_HI - Y_LO), stops)}"/>'
        for x, y in sorted(pts, key=lambda p: (p[1], p[0])))
    return f'<g transform="translate({dx:.2f} {dy:.2f})">\n    {body}\n  </g>'


HEAD = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="100" '
        'height="100" role="img" aria-label="Surrogate Engineering">\n'
        '  <title>Surrogate Engineering</title>\n'
        '  <!-- Generated by docs/make_logo.py — do not hand-edit. -->')
TILE = 'x="1.6" y="1.6" width="96.8" height="96.8" rx="21" ry="21"'


def tile_svg(stops=RAMP) -> str:
    """The mark on its paper tile — what `logo.svg` holds, and what the banner sets."""
    return (f'{HEAD}'
            f'\n  <rect {TILE} fill="{PAPER}"/>'
            f'\n  {dots(stops)}'
            f'\n  <rect {TILE} fill="none" stroke="{LINE2}" stroke-width="1.4"/>'
            f'\n</svg>\n')


PUBLIC = HERE.parent / "engine-copilot/frontend/public"


def build() -> None:
    plain = f"{HEAD}\n  {dots()}\n</svg>\n"
    for name, text in (
        ("logo.svg", tile_svg()),
        ("logo-plain.svg", plain),
        ("logo-dark.svg", f"{HEAD}\n  {dots(RAMP_DARK)}\n</svg>\n"),
    ):
        (HERE / name).write_text(text)
        print(f"wrote {HERE / name}")

    # The app's two copies are written from here rather than copied across by hand, which
    # is exactly the kind of step that silently drifts. `favicon.svg` keeps the tile — a
    # browser tab needs its own ground; the sidebar mark sits on the app's paper already,
    # so it takes the plain one.
    if PUBLIC.is_dir():
        for name, text in (("favicon.svg", tile_svg()), ("mark.svg", plain)):
            (PUBLIC / name).write_text(text)
            print(f"wrote {PUBLIC / name}")


if __name__ == "__main__":
    build()
